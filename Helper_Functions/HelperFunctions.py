def load_vectors_from_files(vector_directory,profile_limit=None):
    """
    Load vectors and their corresponding identifiers from the given directory.
    """
    vectors_list = []
    identifiers = []  # List to store numeric identifiers
    # Collect all valid vector files
    vector_files = [f for f in os.listdir(vector_directory) if f.endswith('_vector.txt')]
    # Ensuring numeric sorting for consistency (e.g., ['1_vector.txt', '10_vector.txt', '2_vector.txt'] → sorted)
    vector_files.sort(key=lambda x: int(x.split('_')[0]))
 
    # Apply profile limit if specified
    if profile_limit:
        vector_files = vector_files[:profile_limit]
    for file_name in vector_files:
        file_path = os.path.join(vector_directory, file_name)
        with open(file_path, 'r') as file:
            vector_str = file.read().strip()
            try:
                vector = np.fromstring(vector_str, sep=' ')
                if vector.size > 0:  # Ensure it's not an empty vector
                    vectors_list.append(vector)

                    # Extract numeric identifier from file name
                    identifier = int(file_name.split('_')[0])
                    identifiers.append(identifier)
                else:
                    print(f"Warning: {file_name} contains an empty or invalid vector, skipping.")

            except ValueError:
                print(f"Error: Could not convert the content of {file_name} to a numpy array, skipping.")

    return vectors_list, identifiers


