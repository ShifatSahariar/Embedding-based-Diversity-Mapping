# Keywords / built-ins that should NOT be treated as user variables
_RESERVED = {
    "let", "print", "sum", "avg", "sin", "cos", "tan",
    "LET", "PRINT", "SUM", "AVG", "SIN", "COS", "TAN"
}

_ID_RE = re.compile(r"\b[a-zA-Z][a-zA-Z_0-9]*\b")  # JS-like identifiers
_LET_RE = re.compile(r"^\s*let\s+([a-zA-Z][a-zA-Z_0-9]*)\s*=\s*(.*)$",
                     re.IGNORECASE)

def calc_define_missing_variables(file_path: str, max_auto_defs: int = 5) -> None:
    """Prepend `Let X = N` for each variable used but never declared."""
    file_path = pathlib.Path(file_path)

    declared, used = set(), set()
    lines = file_path.read_text().splitlines(keepends=True)

    for line in lines:
        m = _LET_RE.match(line)
        if m:
            var, rhs = m.group(1), m.group(2)
            declared.add(var)
            used.update(t for t in _ID_RE.findall(rhs) if t not in _RESERVED)
        else:
            used.update(t for t in _ID_RE.findall(line) if t not in _RESERVED)

    missing = [v for v in used - declared]
    if len(missing) == 0:
        return  # nothing to do

    # Limit the auto-definitions to avoid huge preambles
    missing = missing[:max_auto_defs]

    new_defs = [f"let {v} = {random.randint(1, 99)}\n" for v in missing]

    # Avoid adding duplicates if script is re-run
    if lines and lines[0].startswith("let "):
        existing_header = [ln for ln in lines if ln.startswith("let ")]
        new_defs = [d for d in new_defs if d.split()[1] not in
                    {ln.split()[1] for ln in existing_header}]

    file_path.write_text("".join(new_defs + lines))






