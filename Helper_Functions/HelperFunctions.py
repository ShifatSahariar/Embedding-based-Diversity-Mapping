def backup_original_class_file(original_class_directory, className):
    className = f"{className}.class"
    original_class_file = os.path.join(original_class_directory, className)
    # Define the backup file path
    original_class_backup = original_class_file + ".backup"

    # Check if the backup already exists; if not, create it
    if not os.path.exists(original_class_backup):
        print("Creating a backup of the original class file.")
        shutil.copyfile(original_class_file, original_class_backup)
    else:
        print("Backup of the original class file already exists.")

    return original_class_backup


def generate_input_files(output_directory, number_of_files_to_generate, sentences_per_file, fuzzer,
                         subject_program):
    """
        Generating inputs as text files containing sentences generated by a fuzzer

        - Removing all existing files from the output directory to ensure it is clean before generating new files.
        - Re-creating the output directory to store the newly generated files.
        - Fuzzer may result in multiple sentences per fuzz due to the nature of the grammar rules
        (e.g., `stat+` in the grammar).
        - Appending "exit" command at the end of each file to signal the end.


        Example:
            generate_files("output_dir", 1000, 1, fuzzer)
            This will generate 1000 files, each with one sentence per file.
            :param fuzzer: Fuzzer instance used to generate sentences based on the grammar.
            :param sentences_per_file:The number of sentences to generate per file.
            :param subject_program: For which SUT program we are generating the INPUTS
            :param number_of_files_to_generate: The number of files to generate.
            :param output_directory: Directory where generated files will be saved.
        """
    # Remove all existing files from output directory
    if os.path.exists(output_directory):
        shutil.rmtree(output_directory)
    # Create new empty directory to re-generate input files
    os.makedirs(output_directory)

    # Config eof_marker: if we need to end the input with some specific keywords
    # depending on the subject program,
    # pass eof_marker depending on the subject program
    # - such as CALC need to add 'exit' end of the input file
    if subject_program == 'CALC':
        eof_marker = "exit"
    elif subject_program == 'basic':
        eof_marker = "bye"
    else:
        eof_marker = None

    # Generate files
    for file_number in range(1, number_of_files_to_generate + 1):
        # filename with number
        filename = os.path.join(output_directory, f"{file_number}.txt")
        with open(filename, "w") as f:
            # Generating sentences per file
            for _ in range(sentences_per_file):
                # Fuzzer will generate sometime more than one sentences : cause
                # in our grammar rule we have stat+
                f.write(fuzzer.fuzz())
                # Append the end-of-file marker if provided
            if eof_marker:
                f.write(f"\n{eof_marker}\n")


