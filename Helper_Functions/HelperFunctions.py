def get_fraction_value(fraction_str):
    """
        Convert a fraction string (e.g., '2/3') to its float equivalent.

        Args:
            fraction_str: A string representing a fraction.

        Returns:
            The float value of the fraction.
        """
    numerator, denominator = map(int, fraction_str.split('/'))
    return numerator / denominator


def calculate_rse(mean, std_dev, n):
    """
    Relative Standard Error (RSE).
    """
    rse = (std_dev / (mean * math.sqrt(n)))
    return rse

def extract_exception_type(exception_msg):
    if not exception_msg or exception_msg.strip().lower() in ["<no_exception>", "no exceptions occurred."]:
        return "<no_exception>"

    if exception_msg.strip().lower() == "<timeout>":
        return "<timeout>"

    for line in exception_msg.strip().splitlines():
        line = line.strip()
        lower_line = line.lower()
        if line.startswith("java.") or "exception" in lower_line or "error" in lower_line:
            exception_type = line.split(":")[0].strip()
            return exception_type.split(".")[-1].lower()

    return "<unknown_exception>"

