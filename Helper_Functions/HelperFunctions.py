def extract_exception(stderr, stdout=None):
    """
    Extracts exception messages from stderr or stdout.

    Returns the full first line of any known exception or error.
    """

    def decode_output(output):
        return output.decode('utf-8') if isinstance(output, bytes) else output

    stderr_decoded = decode_output(stderr)
    stdout_decoded = decode_output(stdout) if stdout else ""

    # Prefer stderr
    for line in stderr_decoded.splitlines():
        line = line.strip()
        if "Exception" in line or "Error" in line:
            return line

    # Fall back to stdout (for interpreters that write exceptions to stdout)
    for line in stdout_decoded.splitlines():
        line = line.strip()
        if "Exception" in line or "Error" in line:
            return line

    return "<no_exception>"


def clear_directory(directory):
    """
    :param directory: we want to clear the directory so that we can write again new files
    :return:
    """
    # Check if the directory exists
    if not os.path.exists(directory):
        print(f"The directory {directory} does not exist.")
        return

    # Remove all files in the directory
    for filename in os.listdir(directory):
        file_path = os.path.join(directory, filename)
        try:
            if os.path.isfile(file_path) or os.path.islink(file_path):
                os.unlink(file_path)
            elif os.path.isdir(file_path):
                shutil.rmtree(file_path)
        except Exception as e:
            print(f"Failed to delete {file_path}. Reason: {e}")


